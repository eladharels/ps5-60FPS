#!/usr/bin/env python3
"""Embed files as NUL-terminated C strings.

Usage: embed.py <output.c> <symbol>=<file> [<symbol>=<file> ...]
"""

import sys


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    out = ["/* Generated by tools/embed.py. Do not edit. */"]
    for arg in sys.argv[2:]:
        sym, path = arg.split("=", 1)
        with open(path, "rb") as f:
            data = f.read()
        if b"\0" in data:
            sys.exit("%s contains NUL bytes" % path)
        out.append("const char %s[] = {" % sym)
        for i in range(0, len(data), 16):
            out.append("  " + ",".join("0x%02x" % b for b in data[i:i + 16]) + ",")
        out.append("  0x00\n};")
    with open(sys.argv[1], "w") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
